// Writes THIRD-PARTY-NOTICES.md: the licence of every open-source package bundled into RackDraw (the web app and the
// desktop app's page). Run `npm run notices` after adding or updating a dependency the app imports.
//
// Starts from the packages the app's code imports and follows their runtime dependencies. Next.js is a build tool here
// (the app is a static export): only its client runtime ends up in the bundle, so its own dependencies are not
// followed except the client helpers it ships. Electron and Chromium bring their own licence files into the installer.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOTS = ['react', 'react-dom', '@xyflow/react', 'zustand', 'fflate', 'idb-keyval', 'jspdf', 'pdfjs-dist', 'html-to-image', 'next'];
const NEXT_CLIENT = ['@swc/helpers'];

/** The folder of a package as Node would resolve it from `from` (a package folder). */
function locate(name, from) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const p = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(p, 'package.json'))) return p;
    if (path.dirname(dir) === dir) return null;
  }
}

const found = new Map();
// Type declarations aren't code, and @napi-rs/canvas is pdf.js's Node-only canvas (the app uses the browser's).
const NOT_BUNDLED = (name) => name.startsWith('@types/') || name.startsWith('@napi-rs/');

function visit(name, from) {
  if (NOT_BUNDLED(name)) return;
  const dir = locate(name, from);
  if (!dir) return;
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const key = `${pkg.name}@${pkg.version}`;
  if (found.has(key)) return;
  found.set(key, { dir, pkg });
  const deps = pkg.name === 'next' ? NEXT_CLIENT : Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies });
  for (const d of deps) visit(d, dir);
}
for (const r of ROOTS) visit(r, root);

const licenceText = (dir) => {
  const f = fs.readdirSync(dir).find((n) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(n));
  return f ? fs.readFileSync(path.join(dir, f), 'utf8').trim() : null;
};
const licenceOf = (pkg) => (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ')) || 'see package';

const list = [...found.values()].sort((a, b) => a.pkg.name.localeCompare(b.pkg.name));
const out = [
  '# Third-party notices',
  '',
  'RackDraw is released under the MIT licence (see LICENSE). It includes the open-source packages below; each is used',
  'under its own licence, reproduced here. The desktop app also includes Electron and Chromium, whose licences are',
  'installed with it (LICENSE.electron.txt and LICENSES.chromium.html).',
  '',
  'This file is generated by `npm run notices` (scripts/third-party-notices.mjs).',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...list.map(({ pkg }) => `| ${pkg.name} | ${pkg.version} | ${licenceOf(pkg)} |`),
  '',
];
for (const { dir, pkg } of list) {
  const text = licenceText(dir);
  out.push(`## ${pkg.name} ${pkg.version}`, '', `Licence: ${licenceOf(pkg)}${pkg.homepage ? ` · ${pkg.homepage}` : ''}`, '');
  out.push(text ? ['```text', text.replace(/```/g, "'''"), '```'].join('\n') : '(No licence file in the package; see its licence field above.)', '');
}
fs.writeFileSync(path.join(root, 'THIRD-PARTY-NOTICES.md'), out.join('\n').replace(/\r\n/g, '\n'));
console.log(`THIRD-PARTY-NOTICES.md: ${list.length} packages`);
for (const { pkg } of list) if (!licenceText(found.get(`${pkg.name}@${pkg.version}`).dir)) console.log(`  no licence file: ${pkg.name}@${pkg.version} (${licenceOf(pkg)})`);
